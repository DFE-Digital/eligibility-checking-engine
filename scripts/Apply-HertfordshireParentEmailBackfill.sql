-- Pilot preview: what will change (before state)
SELECT p.Reference, a.ParentFirstName, a.ParentLastName, a.ChildFirstName, a.EstablishmentId,
       a.Status, a.ParentEmail AS CurrentEmail, s.ParentEmail AS WillBecome, s.Source, s.EmailType, a.Updated
FROM dbo.zz_HertsEmailBackfill_Pilot p
