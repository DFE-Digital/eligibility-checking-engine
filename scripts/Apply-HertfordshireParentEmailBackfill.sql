-- =============================================================================
-- Hertfordshire (LocalAuthorityID 919) ParentEmail backfill - APPLY
-- =============================================================================
-- Background:
--   See Analyse-HertfordshireParentEmailBackfill.sql. The June 2026 bulk
--   import (25-26 Jun) loaded ~19.5k live FSM applications without a parent
--   email. Hertfordshire approved (06/11/2026) a mapping of application
--   reference -> email taken from the same family's earlier imported record
--   (tab A: 18,122 unambiguous; tab B resolved by the agreed rule: 252).
--
-- What this script does:
--   Copies the APPROVED emails from dbo.zz_HertsEmailBackfill_Stage onto
--   dbo.Applications, filling blanks only. Nothing is recomputed here - what
--   Hertfordshire signed off is exactly what is applied.
--
-- *** RUN AGAINST THE PRIMARY DATABASE (EligibilityCheck), NOT read-replica ***
--
-- Prerequisites:
--   1. Hertfordshire's written approval of tabs A and B-resolved.
--   2. Stage-HertsEmail.sql (generated by Convert-HertsEmailStaging.ps1 from
--      the approved workbooks) has been run, creating and populating
--      dbo.zz_HertsEmailBackfill_Stage.
--   3. A DB backup / point-in-time restore window exists (Azure SQL PITR is
--      on by default; note the time you start).
--
-- How to run - section by section, reading each result before the next:
--   1. PREVIEW      - assertions. Every "Problem" count must be 0.
--   2. PILOT LIST   - insert ~10 references, re-run the preview for them.
--   3. APPLY        - @Mode = 'pilot' first. Check the portal. Then 'full'.
--   4. VERIFY       - applied = staged, 0 remaining blanks, 0 mismatches.
--   5. ROLLBACK     - commented out; restores from the backup table.
--   6. CLEAN-UP     - commented out; keep the backup table for 30 days.
--
-- Safety:
--   - Only rows where ParentEmail is NULL/blank are touched (final guard in
--     the UPDATE itself, so it is idempotent - re-running skips done rows).
--   - Every change is captured by OUTPUT into dbo.zz_HertsEmailBackfill_Backup
--     (old value, old Updated, new value, when, mode) in the same statement.
--   - Batched (2,000 rows / transaction) so locks are short; the whole run
--     is ~18k single-row updates on a 69 MB table - seconds, not minutes.
-- =============================================================================

SET NOCOUNT ON;
SET XACT_ABORT ON;
GO

-- Hard stop if someone runs this on the replica by mistake
IF DB_NAME() <> 'EligibilityCheck'
    THROW 50000, 'Wrong database - this must run against the PRIMARY (EligibilityCheck).', 1;
IF OBJECT_ID('dbo.zz_HertsEmailBackfill_Stage') IS NULL
    THROW 50000, 'dbo.zz_HertsEmailBackfill_Stage not found - run Stage-HertsEmail.sql first.', 1;
GO

-- Backup / audit table - created once, appended to by every apply run
IF OBJECT_ID('dbo.zz_HertsEmailBackfill_Backup') IS NULL
CREATE TABLE dbo.zz_HertsEmailBackfill_Backup (
    ApplicationID   NVARCHAR(450) NOT NULL PRIMARY KEY,
    Reference       VARCHAR(8)    NOT NULL,
    OldParentEmail  VARCHAR(1000) NULL,
    OldUpdated      DATETIME2     NOT NULL,
    NewParentEmail  VARCHAR(1000) NOT NULL,
    AppliedAt       DATETIME2     NOT NULL,
    Mode            VARCHAR(10)   NOT NULL
);

-- Pilot list - populated in section 2
IF OBJECT_ID('dbo.zz_HertsEmailBackfill_Pilot') IS NULL
CREATE TABLE dbo.zz_HertsEmailBackfill_Pilot (Reference VARCHAR(8) NOT NULL PRIMARY KEY);
GO

-- -----------------------------------------------------------------------------
-- 1. PREVIEW - run this first. No data is changed.
--    Every row in the "Problem" result set must show 0. If not, STOP.
-- -----------------------------------------------------------------------------
;WITH j AS (
    SELECT s.Reference, s.ParentEmail AS StagedEmail, s.Source,
           a.ApplicationID, a.LocalAuthorityID, a.Status, a.Created,
           NULLIF(LTRIM(RTRIM(a.ParentEmail)), '') AS CurrentEmail
    FROM dbo.zz_HertsEmailBackfill_Stage s
    LEFT JOIN dbo.Applications a ON a.Reference = s.Reference
)
SELECT 'staged rows'                                         AS Metric, COUNT(*) AS Value FROM j
UNION ALL SELECT '  from tab A',                                       COUNT(*) FROM j WHERE Source = 'A'
UNION ALL SELECT '  from tab B resolved',                              COUNT(*) FROM j WHERE Source = 'B'
UNION ALL SELECT 'READY: blank email, all checks pass',                COUNT(*) FROM j
          WHERE ApplicationID IS NOT NULL AND CurrentEmail IS NULL AND LocalAuthorityID = 919
            AND Status <> 'Archived' AND Created >= '2026-06-25' AND Created < '2026-07-01'
UNION ALL SELECT 'already has the staged email (done / re-run)',       COUNT(*) FROM j WHERE CurrentEmail = StagedEmail
UNION ALL SELECT 'Problem: reference not found',                       COUNT(*) FROM j WHERE ApplicationID IS NULL
UNION ALL SELECT 'Problem: LocalAuthorityID <> 919',                   COUNT(*) FROM j WHERE LocalAuthorityID <> 919
UNION ALL SELECT 'Problem: status is Archived',                        COUNT(*) FROM j WHERE Status = 'Archived'
UNION ALL SELECT 'Problem: created outside 25 Jun - 30 Jun 2026',      COUNT(*) FROM j WHERE Created < '2026-06-25' OR Created >= '2026-07-01'
UNION ALL SELECT 'Problem: has a DIFFERENT email already (will skip)', COUNT(*) FROM j WHERE CurrentEmail IS NOT NULL AND CurrentEmail <> StagedEmail
UNION ALL SELECT 'Problem: staged email not plausible',                COUNT(*) FROM j WHERE StagedEmail NOT LIKE '%_@_%._%';
GO

-- Detail of anything flagged above (expect 0 rows)
SELECT s.Reference, s.Source, s.ParentEmail AS StagedEmail,
       a.LocalAuthorityID, a.Status, a.Created, a.ParentEmail AS CurrentEmail,
       CASE WHEN a.ApplicationID IS NULL THEN 'not found'
            WHEN a.LocalAuthorityID <> 919 THEN 'wrong LA'
            WHEN a.Status = 'Archived' THEN 'archived'
            WHEN a.Created < '2026-06-25' OR a.Created >= '2026-07-01' THEN 'outside June window'
            WHEN NULLIF(LTRIM(RTRIM(a.ParentEmail)), '') IS NOT NULL
             AND a.ParentEmail <> s.ParentEmail THEN 'different email present'
       END AS Problem
FROM dbo.zz_HertsEmailBackfill_Stage s
LEFT JOIN dbo.Applications a ON a.Reference = s.Reference
WHERE a.ApplicationID IS NULL
   OR a.LocalAuthorityID <> 919
   OR a.Status = 'Archived'
   OR a.Created < '2026-06-25' OR a.Created >= '2026-07-01'
   OR (NULLIF(LTRIM(RTRIM(a.ParentEmail)), '') IS NOT NULL AND a.ParentEmail <> s.ParentEmail);
GO

-- -----------------------------------------------------------------------------
-- 2. PILOT LIST - choose ~10 references to apply first.
--    The SELECT proposes a mix (parent / school-office emails, tab A / tab B,
--    Receiving / Entitled). Review it, then either INSERT the proposed set or
--    hand-pick references from the approved workbook.
-- -----------------------------------------------------------------------------
;WITH pool AS (
    SELECT s.Reference, s.Source, s.EmailType, a.Status, a.EstablishmentId,
           ROW_NUMBER() OVER (PARTITION BY s.Source,
                                           CASE WHEN s.EmailType = 'parent' THEN 'p' ELSE 'o' END,
                                           a.Status
                              ORDER BY NEWID()) AS rn
    FROM dbo.zz_HertsEmailBackfill_Stage s
    JOIN dbo.Applications a ON a.Reference = s.Reference
    WHERE NULLIF(LTRIM(RTRIM(a.ParentEmail)), '') IS NULL
)
SELECT TOP 10 Reference, Source, EmailType, Status, EstablishmentId
FROM pool
WHERE rn = 1
ORDER BY Source, EmailType, Status;
GO

